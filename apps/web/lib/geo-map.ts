// Project lon/lat (equirectangular) to SVG x/y in a 1000x500 viewBox.
export function toXY(lon: number, lat: number, W = 1000, H = 500) {
  const x = ((lon + 180) / 360) * W;
  const y = ((90 - lat) / 180) * H;
  return { x, y };
}
